//! Phase 9.5.6c — freeze a live FFI wrapper into a standalone module dylib.
//!
//! A loaded `Module` + its declarative wraps are M_USER facts. `freeze`:
//!   1. reconstructSource — walk every `:ffi-path` module + its wraps and emit
//!      canonical birnam source (`let mN := [Module load: "p"]; [mN wrap: #sel
//!      as: "sym" signature: "sig"]; ...`). This alone is a portable,
//!      re-editable, `:in`-able wrapper unit.
//!   2. writeArtifacts — write `<base>.birnam`, a `<base>.zig` wrapper module
//!      (embeds the source, `@import`s the shared ABI mirror, and at
//!      `birnam_module_init` sends `fileInSource:` to the `language` prototype),
//!      and a copy of `birnam_module_abi.zig`.
//!   3. compile — `zig build-lib` the wrapper into `lib<base>.dylib`.
//!
//! Loading that dylib (after peg + lang) causes its init to re-file-in the
//! wraps — which `Module load:` opens the alien lib + binds the symbols. No new
//! kernel ABI: the frozen module just replays the same sends file-in does.

const std = @import("std");
const fact_store_mod = @import("fact_store.zig");
const interner_mod = @import("interner.zig");
const kernel_eids = @import("kernel_eids.zig");
const ref_mod = @import("ref.zig");
const strings = @import("strings.zig");

/// Bytes of the shared ABI mirror, baked in so `writeArtifacts` can drop a
/// copy next to the generated wrapper for a standalone `zig build-lib`.
const ABI_MIRROR = @embedFile("module_abi.zig");

pub const Stats = struct { modules: usize, wraps: usize };

/// Reconstruct canonical birnam wrapper source from every `:ffi-path` module
/// in the store and its declarative wraps. Caller frees the returned slice.
pub fn reconstructSource(
    allocator: std.mem.Allocator,
    store: *const fact_store_mod.FactStore,
    interner: *const interner_mod.Interner,
) ![]u8 {
    var buf = std.ArrayList(u8){};
    errdefer buf.deinit(allocator);
    const w = buf.writer(allocator);

    try w.writeAll("// birnam FFI wrapper — generated by freeze.\n");

    var mods = store.entitiesWith(kernel_eids.ATTR_FFI_PATH);
    var n: usize = 0;
    var stats = Stats{ .modules = 0, .wraps = 0 };
    while (mods.next()) |me| {
        const mod_eid = me.e;
        const path_ref = store.currentValue(mod_eid, kernel_eids.ATTR_FFI_PATH) orelse continue;
        if (!strings.isString(path_ref)) continue;
        const var_name = n;
        n += 1;
        stats.modules += 1;
        try w.print("let m{d} := [Module load: \"{s}\"];\n", .{ var_name, strings.bytes(path_ref) });

        var wraps = store.entitiesMatching(kernel_eids.ATTR_FFI_OWNER, ref_mod.mkEid(mod_eid));
        while (wraps.next()) |wrap_eid| {
            const sym_ref = store.currentValue(wrap_eid, kernel_eids.ATTR_FFI_WRAP_SYMBOL) orelse continue;
            const sig_ref = store.currentValue(wrap_eid, kernel_eids.ATTR_FFI_SIG_STR) orelse continue;
            const sel_ref = store.currentValue(wrap_eid, kernel_eids.ATTR_WRAP_SELECTOR) orelse continue;
            if (!strings.isString(sym_ref) or !strings.isString(sig_ref) or !ref_mod.isEid(sel_ref)) continue;
            const sel_name = interner.nameOf(ref_mod.untagEid(sel_ref)) orelse continue;
            try w.print(
                "[m{d} wrap: #{s} as: \"{s}\" signature: \"{s}\"];\n",
                .{ var_name, sel_name, strings.bytes(sym_ref), strings.bytes(sig_ref) },
            );
            stats.wraps += 1;
        }
    }
    return buf.toOwnedSlice(allocator);
}

/// The `<base>.zig` wrapper-module template. Embeds `<base>.birnam`, imports
/// the shared ABI mirror, and on init re-files-in the source via the `language`
/// prototype's `fileInSource:`.
fn wrapperZig(allocator: std.mem.Allocator, basename: []const u8) ![]u8 {
    return std.fmt.allocPrint(allocator,
        \\//! Generated FFI wrapper module — `zig build-lib` me into a dylib,
        \\//! then load after peg + lang. My init re-establishes the wraps.
        \\const abi = @import("birnam_module_abi.zig");
        \\const SRC = @embedFile("{s}.birnam");
        \\
        \\var g_api: *const abi.IdApi = undefined;
        \\
        \\export fn birnam_module_init(
        \\    ctx: *abi.ShellContext,
        \\    api: *const abi.IdApi,
        \\    module_eid: u64,
        \\) callconv(.c) void {{
        \\    _ = ctx;
        \\    _ = module_eid;
        \\    g_api = api;
        \\    const sel = api.intern("fileInSource:", 13);
        \\    _ = api.send1(abi.mkEid(abi.LANGUAGE_PROTO), sel, api.make_string(SRC, SRC.len));
        \\}}
        \\
    , .{basename});
}

/// Write `<dir>/<base>.birnam`, `<dir>/<base>.zig`, and a copy of the ABI
/// mirror into `dir`. Returns reconstruction stats.
pub fn writeArtifacts(
    allocator: std.mem.Allocator,
    store: *const fact_store_mod.FactStore,
    interner: *const interner_mod.Interner,
    dir: std.fs.Dir,
    basename: []const u8,
) !Stats {
    const source = try reconstructSource(allocator, store, interner);
    defer allocator.free(source);

    const birnam_name = try std.fmt.allocPrint(allocator, "{s}.birnam", .{basename});
    defer allocator.free(birnam_name);
    try dir.writeFile(.{ .sub_path = birnam_name, .data = source });

    const zig_src = try wrapperZig(allocator, basename);
    defer allocator.free(zig_src);
    const zig_name = try std.fmt.allocPrint(allocator, "{s}.zig", .{basename});
    defer allocator.free(zig_name);
    try dir.writeFile(.{ .sub_path = zig_name, .data = zig_src });

    try dir.writeFile(.{ .sub_path = "birnam_module_abi.zig", .data = ABI_MIRROR });

    // Recompute stats (cheap second pass; reconstructSource already wrote).
    var stats = Stats{ .modules = 0, .wraps = 0 };
    var mods = store.entitiesWith(kernel_eids.ATTR_FFI_PATH);
    while (mods.next()) |me| {
        if (store.currentValue(me.e, kernel_eids.ATTR_FFI_PATH) == null) continue;
        stats.modules += 1;
        var wraps = store.entitiesMatching(kernel_eids.ATTR_FFI_OWNER, ref_mod.mkEid(me.e));
        while (wraps.next()) |_| stats.wraps += 1;
    }
    return stats;
}

/// `zig build-lib <dir>/<base>.zig -dynamic` → `<dir>/lib<base>.dylib`.
/// Best-effort: returns the child's term. Requires `zig` on PATH.
pub fn compile(allocator: std.mem.Allocator, dir_path: []const u8, basename: []const u8) !std.process.Child.Term {
    const zig_rel = try std.fmt.allocPrint(allocator, "{s}.zig", .{basename});
    defer allocator.free(zig_rel);
    const name_arg = try std.fmt.allocPrint(allocator, "{s}", .{basename});
    defer allocator.free(name_arg);

    var child = std.process.Child.init(
        &.{ "zig", "build-lib", zig_rel, "-dynamic", "-fPIC", "--name", name_arg },
        allocator,
    );
    child.cwd = dir_path;
    child.stdout_behavior = .Inherit;
    child.stderr_behavior = .Inherit;
    try child.spawn();
    return try child.wait();
}
